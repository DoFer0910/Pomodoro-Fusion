import { test, expect, type Page } from "@playwright/test"

const project = { id: "p", name: "ZECT 開発案件", hourlyRate: 2500, color: "#22c55e", createdAt: 1, updatedAt: 1, repoPaths: ["D:/yield-fixture"] }
async function initialize(page: Page, records?: unknown) {
  await page.clock.install({ time: new Date("2026-10-12T08:59:00+09:00") })
  await page.clock.pauseAt(new Date("2026-10-12T09:00:00+09:00"))
  await page.addInitScript(({ project, records }) => {
    if (!localStorage.getItem("pomodoro-projects")) localStorage.setItem("pomodoro-projects", JSON.stringify([project]))
    if (records && !localStorage.getItem("yield-attendance")) localStorage.setItem("yield-attendance", JSON.stringify(records))
    localStorage.setItem("pomodoro-settings", JSON.stringify({ language: "ja", allowOvertime: false, workDuration: 1, alarmSound: "none" }))
  }, { project, records })
  await page.goto("/")
  await expect(page.getByRole("button", { name: "勤務開始", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "勤務記録", exact: true }).click()
  await expect(page.getByRole("button", { name: "勤務開始", exact: true })).toBeVisible()
}

test("勤務開始→休憩→再開→終了→確定→コピーを通し、修正すると再確認に戻る", async ({ page, context }) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"])
  await initialize(page)
  await page.getByLabel("勤務プロジェクト", { exact: true }).selectOption("p")
  await page.getByRole("button", { name: "勤務開始", exact: true }).click()
  await expect(page.getByRole("button", { name: "休憩に入る" })).toBeVisible()
  await page.clock.fastForward(3600000)
  await page.getByRole("button", { name: "休憩に入る" }).click()
  await expect(page.getByRole("button", { name: "勤務再開" })).toBeVisible()
  await page.clock.fastForward(1800000)
  await page.getByRole("button", { name: "勤務再開" }).click()
  await expect(page.getByRole("button", { name: "休憩に入る" })).toBeVisible()
  await page.clock.fastForward(3600000)
  await page.getByRole("button", { name: "勤務終了", exact: true }).click()
  await expect(page.getByTestId("daily-work-time")).toHaveText("2:00:00")
  await expect(page.getByTestId("daily-break-time")).toHaveText("0:30:00")
  await page.getByRole("button", { name: "この日の記録を確定" }).click()
  await expect(page.getByRole("button", { name: "この日の記録を確定" })).toBeDisabled()
  await page.getByRole("button", { name: "確定した日別時間をコピー" }).click()
  await expect(page.getByText("日別の勤務時間をコピーしました。")).toBeVisible()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe("2026-10-12\t2:00:00")
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: "test-results/work-records-desktop.png" })
  await page.getByRole("button", { name: "区間を編集", exact: true }).first().click()
  await page.getByLabel("開始日時", { exact: true }).fill("2026-10-12T09:15")
  await page.getByRole("button", { name: "保存", exact: true }).click()
  await expect(page.getByTestId("daily-work-time")).toHaveText("1:45:00")
  await expect(page.getByRole("button", { name: "この日の記録を確定" })).toBeEnabled()
  await expect(page.getByRole("textbox", { name: "転記用の日別一覧" })).toHaveValue("")
  await page.reload()
  await page.getByRole("button", { name: "勤務記録", exact: true }).click()
  await expect(page.getByTestId("daily-work-time")).toHaveText("1:45:00")
})

test("ポモドーロの終了・休憩移行で勤務計測を止めない", async ({ page }) => {
  await initialize(page)
  await page.getByRole("button", { name: "勤務開始", exact: true }).click()
  await expect(page.getByRole("button", { name: "休憩に入る" })).toBeVisible()
  await page.getByRole("button", { name: "タイマー", exact: true }).click()
  await page.getByRole("button", { name: "スタート", exact: true }).click()
  await page.clock.runFor(61000)
  await expect(page.getByRole("button", { name: "勤務終了", exact: true })).toBeVisible()
  await expect(page.getByRole("button", { name: "休憩に入る" })).toBeVisible()
  const attendance = await page.evaluate(() => JSON.parse(localStorage.getItem("yield-attendance")!))
  expect(attendance.records).toHaveLength(1)
  expect(attendance.records[0].end).toBeNull()
  expect(attendance.records[0].kind).toBe("work")
  await page.getByRole("button", { name: "Compact Mode", exact: true }).click()
  await page.getByRole("button", { name: "勤務を計測中 · 勤務記録", exact: true }).click()
  await expect(page.getByRole("heading", { name: "勤務記録", exact: true })).toBeVisible()
})

test("再起動で未終了区間を示し、終了時刻を修正して確定できる", async ({ page }) => {
  await initialize(page)
  await page.getByRole("button", { name: "勤務開始", exact: true }).click()
  await page.clock.fastForward(3600000)
  await page.reload()
  await page.getByRole("button", { name: "勤務記録", exact: true }).click()
  await expect(page.getByText(/終了していない記録が残っています/)).toBeVisible()
  await page.getByRole("button", { name: "この日の記録を確定" }).click()
  await expect(page.getByText(/この日に終了していない区間があります/)).toBeVisible()
  await page.getByRole("button", { name: "区間を編集", exact: true }).click()
  await page.getByLabel("終了日時", { exact: true }).fill("2026-10-12T09:45")
  await page.getByRole("button", { name: "保存", exact: true }).click()
  await expect(page.getByTestId("daily-work-time")).toHaveText("0:45:00")
  await page.getByRole("button", { name: "この日の記録を確定" }).click()
  await expect(page.getByRole("textbox", { name: "転記用の日別一覧" })).toHaveValue("2026-10-12\t0:45:00")
})

test("狭い画面で手動追加・重複拒否・修正・削除を操作できる", async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  const start = new Date("2026-10-12T07:00:00+09:00").getTime()
  await initialize(page, { version: 1, records: [{ id: "existing", start, end: start + 3600000, kind: "work", projectId: "p", projectName: project.name }], ignored: [], reviews: {} })
  await page.getByRole("button", { name: "勤務・休憩を追加" }).click()
  await page.getByLabel("開始日時", { exact: true }).fill("2026-10-12T07:30")
  await page.getByLabel("終了日時", { exact: true }).fill("2026-10-12T08:30")
  await page.getByRole("button", { name: "保存", exact: true }).click()
  await expect(page.getByRole("dialog").getByRole("alert")).toHaveText(/他の勤務・休憩区間と重なっています/)
  await expect(page.getByLabel("開始日時", { exact: true })).toHaveValue("2026-10-12T07:30")
  await page.getByLabel("開始日時", { exact: true }).fill("2026-10-12T08:00")
  await page.getByRole("button", { name: "保存", exact: true }).click()
  await expect(page.getByTestId("daily-work-time")).toHaveText("1:30:00")
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: "test-results/work-records-narrow.png" })
  page.on("dialog", dialog => dialog.accept())
  await page.getByRole("button", { name: "区間を削除", exact: true }).last().click()
  await expect(page.getByTestId("daily-work-time")).toHaveText("1:00:00")
})
